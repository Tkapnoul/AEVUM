const DICTS: Record<Locale, Record<MessageKey, string>> = { el, en };

interface I18n {
  locale: Locale;
  t: (key: MessageKey, vars?: Record<string, string | number>) => string;
  fmtDate: (ts: number | string, opts?: Intl.DateTimeFormatOptions) => string;
  fmtNum: (n: number, digits?: number) => string;
}

const Ctx = createContext<I18n | null>(null);

export function I18nProvider({ locale, children }: { locale: Locale; children: ReactNode }) {
  const value = useMemo<I18n>(() => {
    const tag = locale === "el" ? "el-GR" : "en-GB";
    return {
      locale,
      t: (key, vars) => {
        let s: string = DICTS[locale][key] ?? key;
        if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
        return s;
      },
      // 24-hour clock in both languages (Greece and the UK both use it).
      fmtDate: (ts, opts = { day: "numeric", month: "short" }) =>
        new Intl.DateTimeFormat(tag, opts.hour ? { hourCycle: "h23", ...opts } : opts).format(new Date(ts)),
      fmtNum: (n, digits = 0) => new Intl.NumberFormat(tag, { maximumFractionDigits: digits, minimumFractionDigits: 0 }).format(n),
    };
  }, [locale]);
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export function useI18n() {
  const v = useContext(Ctx);
  if (!v) throw new Error("useI18n outside I18nProvider");
  return v;
}

export function detectLocale(): Locale {
  try {
    const saved = localStorage.getItem("aevum.locale");
    if (saved === "el" || saved === "en") return saved;
  } catch {
    /* storage unavailable */
  }
  return navigator.language.toLowerCase().startsWith("el") ? "el" : "en";
}
